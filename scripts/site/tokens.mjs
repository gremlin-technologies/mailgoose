// Writes the public site's design tokens (site/assets/tokens.css) from the web
// app's own, the :root blocks at the top of web/src/styles.css, so the site and
// the app share one set of colors, shadows, radii and type. Run it from the
// repository root after changing the app's tokens:
//
//   node scripts/site/tokens.mjs           # write site/assets/tokens.css
//   node scripts/site/tokens.mjs --check   # exit 1 if it's out of date
//
// web/src/pages/siteTokens.test.ts fails when the two drift apart.
import fs from "node:fs";

const src = "web/src/styles.css";
const out = "site/assets/tokens.css";

const css = fs.readFileSync(src, "utf8");
const start = css.indexOf(":root {");
const end = css.indexOf("\n* {");
if (start < 0 || end < start) throw new Error(`can't find the token blocks in ${src}`);

const tokens = `/* Generated by scripts/site/tokens.mjs from ${src}. Don't edit by hand:
   change the app's tokens, then run \`node scripts/site/tokens.mjs\`. */

/* Inter, self-hosted like the app's (latin subset, variable weight). Its
   licence is in fonts/LICENSE-Inter.txt. */
@font-face {
  font-family: "Inter Variable";
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  src: url("/assets/fonts/inter-latin-wght.woff2") format("woff2");
}

${css.slice(start, end).trimEnd()}
`;

if (process.argv.includes("--check")) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (have !== tokens) {
    console.error(`${out} is out of date: run node scripts/site/tokens.mjs`);
    process.exit(1);
  }
  console.log(`${out} is up to date`);
} else {
  fs.writeFileSync(out, tokens);
  console.log("wrote", out);
}
