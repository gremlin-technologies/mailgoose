// Writes the public site's design tokens (site/assets/tokens.css in the
// public site repository, gremlin-technologies/mailgoose-public) from the web
// app's own, the light :root block at the top of web/src/styles.css, so the
// site and the app share one set of colors, shadows, radii and type. The site
// is light only (owner's call, Nov 21), so the app's dark block stays behind.
// Run it from this repository's root, with the site repository checked out
// next to it, after changing the app's tokens, then open a PR there:
//
//   node scripts/site/tokens.mjs           # write ../mailgoose-public/site/assets/tokens.css
//   node scripts/site/tokens.mjs --check   # exit 1 if it's out of date
//
// SITE_DIR points it at another checkout's site/ folder.
import fs from "node:fs";

const src = "web/src/styles.css";
const out = `${process.env.SITE_DIR || "../mailgoose-public/site"}/assets/tokens.css`;

const css = fs.readFileSync(src, "utf8");
const start = css.indexOf(":root {");
const end = css.indexOf("\n/* Dark mode");
if (start < 0 || end < start) throw new Error(`can't find the light token block in ${src}`);

const tokens = `/* Generated by scripts/site/tokens.mjs in the app repository from ${src}.
   Don't edit by hand: change the app's tokens, then run that script. */

/* Inter, self-hosted like the app's (latin subset, variable weight). Its
   licence is in fonts/LICENSE-Inter.txt. */
@font-face {
  font-family: "Inter Variable";
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  src: url("/assets/fonts/inter-latin-wght.woff2") format("woff2");
}

${css.slice(start, end).trimEnd()}
`;

if (process.argv.includes("--check")) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (have !== tokens) {
    console.error(`${out} is out of date: run node scripts/site/tokens.mjs`);
    process.exit(1);
  }
  console.log(`${out} is up to date`);
} else {
  fs.writeFileSync(out, tokens);
  console.log("wrote", out);
}
