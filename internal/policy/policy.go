// Package policy holds the versions of mailgoose's policies: the terms of
// service, privacy policy, anti-spam policy and data processing agreement
// (MG-68). It is the one place they are kept. The web app's copy,
// web/src/policyVersions.gen.ts, is generated from it by `make generate`.
//
// The four pages are versioned together: signing up accepts the terms and
// the anti-spam policy, and the DPA is part of the terms, so one version
// number covers what a person agreed to. Adding a version here makes every
// account accept it again before its next launch.
package policy

import (
	"encoding/json"
	"fmt"
	"time"
)

// Version is one version of the policies.
type Version struct {
	// ID names the version. It is the date it was written, YYYY-MM-DD, so
	// later versions sort after earlier ones.
	ID string `json:"version"`
	// Effective is the day it takes effect, YYYY-MM-DD.
	Effective string `json:"effective"`
	// Changes says what changed since the version before, one line each.
	Changes []string `json:"changes"`
}

// EffectiveDate is Effective as a date in UTC.
func (v Version) EffectiveDate() time.Time {
	t, err := time.Parse(time.DateOnly, v.Effective)
	if err != nil {
		panic(fmt.Sprintf("policy version %s: bad effective date %q", v.ID, v.Effective))
	}
	return t
}

// Initial is the version that was live when the policy pages were first
// published (MG-57). Accounts that signed up before versions were recorded
// are taken to have accepted it (migration 00036).
const Initial = "2026-11-19"

// history lists every version, oldest first. Add a new one at the end.
var history = []Version{
	{
		ID:        Initial,
		Effective: "2026-11-19",
		Changes: []string{
			"The first version: placeholder outlines of the terms of service, privacy policy, anti-spam policy and data processing agreement.",
		},
	},
}

// Current is the version in force now.
func Current() Version { return history[len(history)-1] }

// History is every version, newest first.
func History() []Version {
	out := make([]Version, 0, len(history))
	for i := len(history) - 1; i >= 0; i-- {
		out = append(out, history[i])
	}
	return out
}

// Known reports whether id is a version that exists.
func Known(id string) bool {
	for _, v := range history {
		if v.ID == id {
			return true
		}
	}
	return false
}

// ChangesPath is the web app's page listing what changed in each version.
const ChangesPath = "/policies/changes"

// WebFile is where `make generate` writes TypeScript().
const WebFile = "web/src/policyVersions.gen.ts"

// TypeScript is the web app's copy of the versions, newest first.
func TypeScript() []byte {
	b, err := json.MarshalIndent(History(), "", "  ")
	if err != nil {
		panic(err)
	}
	return fmt.Appendf(nil, `// Code generated by internal/policy/gen from internal/policy/policy.go. DO NOT EDIT.
// Run make generate after changing the policy versions there.

export type PolicyVersion = { version: string; effective: string; changes: string[] };

/** Every version of the policies, newest first. */
export const policyVersions: PolicyVersion[] = %s;

/** The version in force now. */
export const currentPolicyVersion: PolicyVersion = policyVersions[0];

/** The page listing what changed in each version. */
export const policyChangesPath = %q;
`, b, ChangesPath)
}
